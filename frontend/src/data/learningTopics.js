export const learningTopics = topicDefinitions.map((topic) => ({
  ...topic,
  imageAlt: `Minh họa chủ đề ${topic.title}, không phải ảnh cụ thể của từng từ`,
  colorClass: ['bg-kids-primary/20', 'bg-kids-secondary/15', 'bg-kids-cta/10'][topic.id % 3],
  words: topic.words.map((word, index) => {
    const wordImage =
      (topic.slug === 'animal-world' && animalWordImages[word]) ||
      (topic.slug === 'fruits' && fruitWordImages[word]) ||
      (topic.slug === 'loving-family' && familyWordImages[word]) ||
      (topic.slug === 'familiar-objects' && furnitureWordImages[word]) ||
      (topic.slug === 'transportation' && trafficWordImages[word]) ||
      (topic.slug === 'colors' && colorWordImages[word]) ||
      (topic.slug === 'plants' && plantWordImages[word]) ||
      (topic.slug === 'body-parts' && bodyWordImages[word])

    return {
      id: `${topic.slug}-${index + 1}`,
      word,
      image: wordImage || topic.image,
      hasSpecificImage: Boolean(wordImage),
      imageAlt: wordImage
        ? `Hình ảnh ${word}`
        : `Minh họa chủ đề ${topic.title}; không phải hình ảnh cụ thể của từ ${word}`,
      audio: null,
      phonemes: [],
      pronunciationGuide:
        'Dữ liệu hướng dẫn khẩu hình riêng cho từ này chưa được chuẩn bị. Bé có thể đọc chậm, tự nhiên theo từng tiếng.',
      mouthImage: null,
      tips: 'Ngồi thoải mái, lắng nghe người lớn đọc mẫu và thử lại nhẹ nhàng. Không cần cố ép khẩu hình.',
      mockScore: 76 + ((topic.id * 7 + index * 5) % 23),
    }
  }),
}))

export function getTopicBySlug(slug) {
  return learningTopics.find((topic) => topic.slug === slug)
}
